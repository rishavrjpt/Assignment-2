import matplotlib.pyplot as plt
import numpy as np

fig, axes = plt.subplots(2, 3, figsize=(15, 8))
axes = axes.flatten()

for i in range(5):
    ax = axes[i]
    x = np.linspace(0, 10, 100)
    y = np.sin(x + i * 0.5)
    ax.plot(x, y)
    ax.set_title(f'Subplot {i+1}')
    ax.set_xlabel('X-axis')
    ax.set_ylabel('Y-axis')

if len(axes) > 5:
    fig.delaxes(axes[5])

plt.tight_layout()
plt.show()